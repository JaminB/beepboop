"""The fixture corpus: ``tools/bench/corpus/manifest.yaml`` and its clips.

A corpus is a folder with ``manifest.yaml`` (this schema) and WAV files.
Real corpora are recorded by the owner with ``tools/bench/record_fixture.py``
through the XVF3800 and never committed (ADR 0018, .gitignore); the synthetic
corpus is generated by :mod:`beepboop_bench.synthetic` and is flagged
``synthetic: true`` so a gate run can refuse it.

Clip kinds
    * ``command``  a spoken command; ``transcript`` and ``scenario`` drive stt/e2e
    * ``wake``     a "Hey beepboop" utterance; ``distance_m`` and ``phrase_end_s``
    * ``soak``     long ambient recording with no wake word (false accepts)
    * ``negative`` a non-member voice (speaker-ID impostor trials)
    * ``enroll``   enrolment utterances of a household speaker

Timestamps are seconds from the start of the file. ``speech_end_s`` is the
hand-labelled end of speech (``bench endpoint``); ``phrase_end_s`` the end of
"boop" in wake clips (hit latency).
"""

from __future__ import annotations

from collections.abc import Iterable
from pathlib import Path
from typing import Literal

import yaml
from pydantic import BaseModel, ConfigDict, Field, model_validator

from beepboop_bench.schema import CorpusInfo, Scenario

ClipKind = Literal["command", "wake", "soak", "negative", "enroll"]
Ambient = Literal["quiet", "tv60", "music", "other"]
RecordedThrough = Literal["xvf3800", "synthetic-tts", "other-mic"]

#: The capture channel of the XVF3800 16 kHz firmware that the pipeline uses.
ASR_BEAM_CHANNEL = 0


class Speaker(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    id: str
    kind: Literal["adult", "child", "synthetic"] = "adult"
    note: str = ""


class Clip(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    id: str
    path: str
    kind: ClipKind
    speaker: str | None = None
    transcript: str | None = None
    scenario: Scenario | None = None
    distance_m: float | None = None
    ambient: Ambient = "quiet"
    speech_end_s: float | None = None
    phrase_end_s: float | None = None
    duration_s: float | None = None
    hotwords: list[str] = Field(default_factory=list[str])
    note: str = ""

    @model_validator(mode="after")
    def _consistent(self) -> Clip:
        if self.kind == "command" and not self.transcript:
            msg = f"clip {self.id}: command clips need a transcript"
            raise ValueError(msg)
        if self.kind in ("command", "wake", "enroll") and self.speaker is None:
            msg = f"clip {self.id}: {self.kind} clips need a speaker"
            raise ValueError(msg)
        return self


class CorpusManifest(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    schema_version: Literal[1] = 1
    name: str
    synthetic: bool
    recorded_through: RecordedThrough
    sample_rate: int = 16000
    capture_channel: int = ASR_BEAM_CHANNEL
    channels: int = 1
    consent: str = ""
    recorded_on: str = ""
    speakers: list[Speaker] = Field(default_factory=list[Speaker])
    clips: list[Clip] = Field(default_factory=list[Clip])

    @model_validator(mode="after")
    def _speakers_known(self) -> CorpusManifest:
        ids = {s.id for s in self.speakers}
        if len(ids) != len(self.speakers):
            msg = "duplicate speaker ids"
            raise ValueError(msg)
        clip_ids = [c.id for c in self.clips]
        if len(set(clip_ids)) != len(clip_ids):
            msg = "duplicate clip ids"
            raise ValueError(msg)
        for clip in self.clips:
            if clip.speaker is not None and clip.kind != "negative" and clip.speaker not in ids:
                msg = f"clip {clip.id}: unknown speaker {clip.speaker!r}"
                raise ValueError(msg)
        if not self.synthetic and self.recorded_through != "xvf3800":
            msg = "a non-synthetic corpus must be recorded through the XVF3800 (ROADMAP M0 scope)"
            raise ValueError(msg)
        return self

    @property
    def real(self) -> bool:
        """A corpus whose numbers may feed a gate."""
        return not self.synthetic and self.recorded_through == "xvf3800"

    def of_kind(self, *kinds: ClipKind) -> list[Clip]:
        return [c for c in self.clips if c.kind in kinds]

    def commands(self, scenario: Scenario | None = None) -> list[Clip]:
        return [c for c in self.of_kind("command") if scenario is None or c.scenario == scenario]


class Corpus:
    """A loaded manifest plus the folder it lives in."""

    def __init__(self, root: Path, manifest: CorpusManifest) -> None:
        self.root = root
        self.manifest = manifest

    @classmethod
    def load(cls, root: Path) -> Corpus:
        path = root / "manifest.yaml"
        if not path.is_file():
            msg = f"no corpus manifest at {path}; record one with tools/bench/record_fixture.py"
            raise FileNotFoundError(msg)
        raw = yaml.safe_load(path.read_text(encoding="utf-8"))
        manifest = CorpusManifest.model_validate(raw)
        corpus = cls(root, manifest)
        absent = [c.id for c in manifest.clips if not corpus.clip_path(c).is_file()]
        if absent:
            more = "..." if len(absent) > 5 else ""
            msg = f"corpus {root}: missing clip files for {absent[:5]}{more}"
            raise FileNotFoundError(msg)
        return corpus

    def clip_path(self, clip: Clip) -> Path:
        return self.root / clip.path

    def info(self, soak_hours: float = 0.0) -> CorpusInfo:
        m = self.manifest
        return CorpusInfo(
            path=str(self.root),
            synthetic=m.synthetic,
            recorded_through=m.recorded_through,
            n_clips=len(m.clips),
            n_speakers=len(m.speakers),
            soak_hours=soak_hours,
        )


def write_manifest(root: Path, manifest: CorpusManifest) -> Path:
    root.mkdir(parents=True, exist_ok=True)
    path = root / "manifest.yaml"
    data = manifest.model_dump(mode="json", exclude_defaults=False)
    path.write_text(yaml.safe_dump(data, sort_keys=False, allow_unicode=True), encoding="utf-8")
    return path


def default_corpus_root() -> Path:
    return Path(__file__).resolve().parents[1] / "corpus"


def speakers_with_clips(
    manifest: CorpusManifest, kinds: Iterable[ClipKind]
) -> dict[str, list[Clip]]:
    out: dict[str, list[Clip]] = {}
    for clip in manifest.of_kind(*kinds):
        if clip.speaker is not None:
            out.setdefault(clip.speaker, []).append(clip)
    return out
